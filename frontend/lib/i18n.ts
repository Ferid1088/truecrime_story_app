export type UiMessage = keyof typeof messages.en;

export function uiLocale(): UiLocale {
  if (typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("de")) return "de";
  return "en";
}

export function useUiMessages(locale: UiLocale = uiLocale()) {
  return (key: UiMessage): string => messages[locale][key];
}
