"""Rights classification (Part 23). FOUND does not mean USABLE.

Deterministic, explainable rules on provider metadata and domain:
  owned / licensed           -> user uploads and our own generated cards/maps
  public_domain              -> PD / CC0 licenses (e.g. Wikimedia Commons)
  creative_commons           -> CC BY / BY-SA (attribution required)
  editorial_review_required  -> news and case-source images (may be usable
                                as editorial reporting; a human decides)
  permission_required        -> explicit "all rights reserved" / NC / ND
  do_not_use                 -> stock libraries, watermarks
  unknown                    -> anything else
"""

from __future__ import annotations

import re
from urllib.parse import urlparse

from app.core.ai_config import ai_config

RIGHTS = ("owned", "licensed", "public_domain", "creative_commons",
          "editorial_review_required", "permission_required", "unknown",
          "do_not_use")


def _domain(url: str | None) -> str:
    try:
        return (urlparse(url or "").hostname or "").lower()
    except ValueError:
        return ""


def classify(provider: str, license_name: str | None = None,
             url: str | None = None, page_url: str | None = None,
             watermark: bool = False) -> tuple[str, str]:
    """(rights_status, reason)."""
    blocked = ai_config.visual_search.blocked_domains
    for u in (url, page_url):
        d = _domain(u)
        if d and any(b in d for b in blocked):
            return "do_not_use", f"stock library ({d})"
    if watermark:
        return "do_not_use", "watermark visible"
    if provider in ("upload", "owned"):
        return "owned", "uploaded by the production"
    if provider == "generated":
        return "owned", "generated by the app (map data credited separately)"
    if provider in ("europeana", "dpla"):
        # these report rights as a rightsstatements.org/creativecommons.org URI (or, for some
        # DPLA records, free text) whose vocabulary the generic free-text matching below does
        # not know (a "by-nc-nd" URI would otherwise wrongly match the generic "\bby\b" rule)
        return classify_open_data_rights(license_name)
    lic = (license_name or "").strip().lower()
    if lic:
        if re.search(r"\b(nc|nd)\b|non-?commercial|no ?deriv", lic):
            return "permission_required", f"license restricts use ({license_name})"
        if re.search(r"public domain|\bpd\b|cc0|pdm", lic):
            return "public_domain", f"license: {license_name}"
        if re.search(r"\bcc\b|creative commons|cc-by|by-sa|\bby\b", lic):
            return "creative_commons", f"license: {license_name}"
        if "all rights reserved" in lic or "copyright" in lic:
            return "permission_required", f"license: {license_name}"
    if provider in ("source_page", "lead_source"):
        return ("editorial_review_required",
                f"image from a case source ({_domain(page_url or url)})")
    if provider == "brave_images":
        return ("editorial_review_required",
                f"web image search result, license unknown ({_domain(page_url or url)})")
    return "unknown", "no license information"


_NEWS_OR_OFFICIAL = {"credible_journalism", "local_journalism", "police_record", "court_record",
                     "government_archive", "primary_official", "coroner_record"}
# local TV/newspaper hosts the domain table does not know, or a /news/ page
_NEWS_HOST = re.compile(r"news|times|post|herald|gazette|tribune|journal|daily|courier|"
                        r"abc\d|cbs\d|nbc\d|fox\d|247now|wdtn|whio|wlwt|wcpo|wbns|wkrg|wtoc|wbtv",
                        re.I)


def _news_page(url: str) -> bool:
    try:
        path = urlparse(url).path.lower()
    except ValueError:
        path = ""
    return bool(_NEWS_HOST.search(_domain(url))) or path.startswith(("/news/", "/crime/"))


def classify_open_data_rights(raw_rights: str | None) -> tuple[str, str]:
    """Rights for an archive item whose own field may be a rightsstatements.org /
    creativecommons.org URI (Europeana; modern DPLA records) or free text (older DPLA
    records) — P12. "In Copyright" (and its EDU/NC/OL/RUU/US variants) is kept as
    editorial_review_required (unclear, shown for review), never silently dropped;
    "No Copyright" (NoC-*) is public domain. Anything else falls back to the existing
    free-text classifier."""
    text = (raw_rights or "").strip()
    if not text:
        return "unknown", "no rights information"
    lower = text.lower()
    if "rightsstatements.org" in lower:
        if "/noc-" in lower:
            return "public_domain", f"rightsstatements.org: No Copyright ({text})"
        if "/inc" in lower:
            return "editorial_review_required", f"rightsstatements.org: In Copyright ({text})"
        if "/cne" in lower or "/und" in lower:
            return "editorial_review_required", f"rightsstatements.org: rights not evaluated ({text})"
        return "editorial_review_required", f"rightsstatements.org: unrecognised statement ({text})"
    if "creativecommons.org" in lower:
        if "publicdomain/zero" in lower or "publicdomain/mark" in lower:
            return "public_domain", f"Creative Commons: public domain ({text})"
        if re.search(r"/by-nc|/by-nd", lower):
            return "permission_required", f"Creative Commons: restricts commercial/derivative use ({text})"
        if "/by" in lower:
            return "creative_commons", f"Creative Commons: {text}"
    return classify("open_data", text, None, None)


def allowed(rights_status: str, profile: str | None = None) -> bool:
    if not ai_config.rights.enforce:
        return True
    profile = profile or ai_config.render.profile
    return rights_status in ai_config.rights.allowed_for_render.get(profile, [])


def usable(asset, profile: str | None = None) -> bool:
    """Whether a picture may go into a film: its rights status is allowed for
    the render profile AND, for editorial_review_required, a human approval
    is recorded on the asset (a news photo is never used on a guess). With
    rights.enforce off none of this applies: relevance alone decides."""
    if not allowed(asset.rights_status, profile):
        return False
    if ai_config.rights.enforce and asset.rights_status == "editorial_review_required":
        return asset.editorial_approved_at is not None
    return True


def needs_attribution(rights_status: str) -> bool:
    return rights_status in ai_config.rights.attribution_required


def credit_due(asset) -> bool:
    """The film shows a credit for this picture: its licence asks for one, or its source does."""
    return needs_attribution(asset.rights_status) or asset.provider in ai_config.rights.credit_providers
