def test_a_protected_span_is_put_back_between_numbers():
    assert say("A1 و 5 و COVID-19") == "A1 و خَمْسَة و COVID-19"


def test_the_direction_marks_and_the_kashida_before_digits_are_dropped():
    assert say("‏2026‏") == "أَلْفَان وَسِتَّة وَعِشْرُون"
    assert say("في الـ13 من أغسطس") == "في الثَّالِث عَشَر من أغسطس"


