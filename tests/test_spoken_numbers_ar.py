"""The Arabic number reader (spoken_numbers/ar.py): the words a narrator says for the digits of a text. The expected strings are proposals from the research
(scratchpad/numbers/ar.md) that no native speaker has reviewed yet. Words of the text keep their own spelling; only numbers are rewritten."""

import pytest

from app.documentary.spoken_numbers.ar import Numbers, Options

BIG = 10**15 - 1


def say(text: str, **options) -> str:
    return Numbers(options, BIG).text(text)


