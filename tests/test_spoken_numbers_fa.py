@pytest.mark.parametrize("text", [
    "یه شب تو خونه نشسته بود", "دو هزار و بیست و شش", "پنجم اکتبر", "سی‌ام", "شب بود؛ او گفت: «نه!»", "", "تو که اینجایی؟ ... بله، من اینجام."])
def test_text_without_digits_stays_the_same(text):
    assert say(text) == text


@pytest.mark.parametrize("text", [
    "سال ۲۰۲۲ با ۹۱۱ تماس گرفت، ساعت ۱۴:۳۰، ۵۰٪ و ۳٫۵ میلیون و $12.50 و ۳ام و ۱۹۹۰-۹۵ و ۹mm و ۱/۲ و +98 21 1234 5678 و ۱۶ فوریه ۲۰۲۶ و .38 و -5 و ۰۰۷"])
def test_no_digit_is_left_and_a_second_run_changes_nothing(text):
    once = say(text)
    assert not any(char.isdigit() for char in once)
    assert say(once) == once


@pytest.mark.parametrize("text", ["https://example.com/5/3", "yaz@site2.com", "A1", "3D", "5G", "4x4", "COVID-19", "F-16", "mp3"])
def test_protected_spans_are_kept(text):
    assert say(text) == text


def test_a_protected_span_next_to_a_number():
    assert say("۵ نفر در COVID-19 و A1 و ۳D مردند") == "پنج نفر در COVID-19 و A1 و ۳D مردند"


def test_the_ordinary_noun_that_is_also_a_month_name_is_no_date_without_a_year():
    assert say("۳ مهر روی سند خورد") == "سه مهر روی سند خورد"
    assert say("۳ مهر ۱۴۰۱") == "سوم مهر هزار و چهارصد و یک"
    assert say("۳ مهر ماه") == "سوم مهر ماه"


def test_a_year_with_the_gregorian_mark_is_not_an_ordinal():
    assert say("۱۹۹۸م") == "هزار و نهصد و نود و هشت میلادی"
    assert say("۱۲م") == "دوازدهم"


def test_a_number_over_the_maximum_is_read_digit_by_digit():
    assert reader_for("fa", {}, 999).text("1000") == "یک صفر صفر صفر"


def test_a_clock_time_that_does_not_exist_is_left_to_the_number_rules():
    assert say("۲۵:۷۰") == "بیست و پنج:هفتاد"


